package com.mallmind.backend.util;

import java.util.ArrayList;
import java.util.List;

/**
 * Minimal, dependency-free CSV line parser: handles quoted fields, embedded
 * commas inside quotes, and escaped quotes ("" -> "). Good enough for the
 * product catalogue import format; not a general RFC 4180 implementation.
 */
public final class SimpleCsvParser {

    private SimpleCsvParser() {
    }

    public static List<String> parseLine(String line) {
        List<String> fields = new ArrayList<>();
        StringBuilder current = new StringBuilder();
        boolean inQuotes = false;

        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (inQuotes) {
                if (c == '"') {
                    if (i + 1 < line.length() && line.charAt(i + 1) == '"') {
                        current.append('"');
                        i++;
                    } else {
                        inQuotes = false;
                    }
                } else {
                    current.append(c);
                }
            } else {
                if (c == '"') {
                    inQuotes = true;
                } else if (c == ',') {
                    fields.add(current.toString());
                    current.setLength(0);
                } else {
                    current.append(c);
                }
            }
        }
        fields.add(current.toString());
        return fields;
    }
}
