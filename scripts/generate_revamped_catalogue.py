    desc = p["description"].replace("'", "''")
    price = p["price"]
    discount = p["discountPrice"] if p.get("discountPrice") is not None else "null"
    specs = sql_quote(p.get("specifications"))
    img = sql_quote(p.get("imageUrl"))
