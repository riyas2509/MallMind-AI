export function getFallbackRoute(fromNodeId: number, toNodeId: number): RouteResponse {
  const targetShop = FALLBACK_SHOPS.find((s) => s.navigationNodeId === toNodeId);
  const targetFacility = FALLBACK_FACILITIES.find((f) => f.navigationNodeId === toNodeId);
  const targetName = targetShop?.name || targetFacility?.label || 'Destination';
  const targetFloor = targetShop?.floorNumber ?? targetFacility?.floorNumber ?? 0;
  const targetX = targetShop?.x ?? targetFacility?.x ?? 500;
  const targetY = targetShop?.y ?? targetFacility?.y ?? 300;

  const startMeta = START_NODE_META[fromNodeId] || {
    floor: 0,
    label: 'Grand Main Entrance (Vastrapur Gate)',
    x: 100,
    y: 300,
  };

  const sameFloor = startMeta.floor === targetFloor;
  const floorLabel = (fl: number) => (fl === -1 ? 'LG' : fl === 0 ? 'Ground Floor (G)' : `Floor ${fl}F`);

  const steps: RouteStep[] = [
    {
      nodeId: fromNodeId,
      floorNumber: startMeta.floor,
      x: startMeta.x,
      y: startMeta.y,
      nodeType: 'ENTRANCE_EXIT',
      label: startMeta.label,
      instruction: `Start at ${startMeta.label} on ${floorLabel(startMeta.floor)}.`,
    },
  ];

  if (!sameFloor) {
    steps.push({
      nodeId: startMeta.floor === 0 ? 23 : 3,
      floorNumber: startMeta.floor,
      x: 500,
      y: 300,
      nodeType: 'ESCALATOR',
      label: 'Central Atrium Vertical Transition',
      instruction: `Walk to the Central Escalator/Elevator core and proceed to ${floorLabel(targetFloor)}.`,
    });
    steps.push({
      nodeId: targetFloor === 0 ? 23 : 3,
      floorNumber: targetFloor,
      x: 500,
      y: 300,
      nodeType: 'CORRIDOR_JUNCTION',
      label: `Concourse on ${floorLabel(targetFloor)}`,
      instruction: `Arrive on ${floorLabel(targetFloor)} concourse and follow aisle signs toward ${targetName}.`,
    });
  } else {
    steps.push({
      nodeId: 23,
      floorNumber: targetFloor,
      x: 500,
      y: 300,
      nodeType: 'CORRIDOR_JUNCTION',
      label: `Central Walkway`,
      instruction: `Proceed along the main walkway on ${floorLabel(targetFloor)} toward ${targetName}.`,
    });
  }

  steps.push({
    nodeId: toNodeId,
    floorNumber: targetFloor,
    x: targetX,
    y: targetY,
    nodeType: targetShop ? 'SHOP_ENTRANCE' : 'FACILITY',
    label: targetName,
    instruction: `Arrive at destination: ${targetName}.`,
  });

  return {
    fromNodeId,
    toNodeId,
    totalDistance: sameFloor ? 80 : 160,
    estimatedDistanceMeters: sameFloor ? 35 : 65,
    isEstimatedDistance: true,
    routeType: sameFloor ? 'SAME_FLOOR_WALK' : 'MULTI_FLOOR_STANDARD',
    steps,
    spokenDirections: steps.map((s) => s.instruction),
  };
}
