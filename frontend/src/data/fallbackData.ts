export function getFallbackFloorMap(floorNumber: number): FloorMapResponse {
  const floor = FALLBACK_FLOORS.find((f) => f.floorNumber === floorNumber) || FALLBACK_FLOORS[1];
  const shops = FALLBACK_SHOPS.filter((s) => s.floorNumber === floorNumber);
  const facilities = FALLBACK_FACILITIES.filter((f) => f.floorNumber === floorNumber);
  return {
    floor,
    shops,
    facilities,
  };
}

