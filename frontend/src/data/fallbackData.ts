export function getFallbackFloorMap(floorNumber: number): FloorMapResponse {
  const floor = FALLBACK_FLOORS.find((f) => f.floorNumber === floorNumber) || FALLBACK_FLOORS[1];
  const shops = FALLBACK_SHOPS.filter((s) => s.floorNumber === floorNumber);
  const facilities = FALLBACK_FACILITIES.filter((f) => f.floorNumber === floorNumber);
  return {
    floor,
    shops,
    facilities,
  };
}

export function getFallbackRoute(fromNodeId: number, toNodeId: number): RouteResponse {
  const targetShop = FALLBACK_SHOPS.find((s) => s.navigationNodeId === toNodeId);
  const targetFacility = FALLBACK_FACILITIES.find((f) => f.navigationNodeId === toNodeId);
  const targetName = targetShop?.name || targetFacility?.label || 'Destination';
  const targetFloor = targetShop?.floorNumber ?? targetFacility?.floorNumber ?? 0;
  const targetX = targetShop?.x ?? targetFacility?.x ?? 500;
  const targetY = targetShop?.y ?? targetFacility?.y ?? 300;

  return {
    fromNodeId,
    toNodeId,
    totalDistance: 120,
    estimatedDistanceMeters: 45,
    isEstimatedDistance: false,
    routeType: 'OPTIMAL_PEDESTRIAN',
    steps: [
      {
        nodeId: fromNodeId,
        floorNumber: 0,
        x: 100,
        y: 300,
        nodeType: 'ENTRANCE_EXIT',
        label: 'Grand Main Entrance (Vastrapur Gate)',
        instruction: 'Start at the Grand Main Entrance and walk towards the Central Atrium.',
      },
      {
        nodeId: 23,
        floorNumber: 0,
        x: 500,
        y: 300,
        nodeType: 'ESCALATOR',
        label: 'Central Atrium Escalators',
        instruction:
          targetFloor === 0
            ? 'Continue along the central concourse towards your destination.'
            : `Take the central escalator to Floor ${targetFloor}.`,
      },
      {
        nodeId: toNodeId,
        floorNumber: targetFloor,
        x: targetX,
        y: targetY,
        nodeType: targetShop ? 'SHOP_ENTRANCE' : 'FACILITY',
        label: targetName,
        instruction: `Arrive at ${targetName}.`,
      },
    ],
    spokenDirections: [
      'Head straight through the Grand Entrance towards the central atrium.',
      targetFloor === 0
        ? `Proceed along the corridor to ${targetName}.`
        : `Take the escalator up to Floor ${targetFloor}.`,
      `You have arrived at ${targetName}.`,
    ],
  };
}
